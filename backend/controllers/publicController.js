/**
 * Records a QR scan for merchant statistics.
 * Deduplicates scans per IP to avoid stat farming.
 */
const recordScan = async (req, res) => {
  try {
    const { code } = req.params;
    const ip = req.ip || req.connection?.remoteAddress || 'unknown';
    const { userAgent = '', source = 'qr_camera' } = req.body;

    const dedupKey = `${ip}:${code.toUpperCase()}`;
    const lastScan = scanDedup.get(dedupKey);
    const now = Date.now();

    if (lastScan && now - lastScan < SCAN_DEDUP_TTL_MS) {
      // Already counted this scan recently — acknowledge without recording
      return res.json({ success: true, message: 'Scan already recorded recently.', deduplicated: true });
    }

    // Mark dedup
    scanDedup.set(dedupKey, now);

    // Clean old entries periodically (every 500 scans)
    if (scanDedup.size > 500) {
      for (const [k, t] of scanDedup.entries()) {
        if (now - t > SCAN_DEDUP_TTL_MS) scanDedup.delete(k);
      }
    }

    // Find the commerce and increment scan count (best-effort, no throw on failure)
    try {
      const scanCommerce = await findCommerceByCode(code);
      if (scanCommerce) {
        await Commerce.findByIdAndUpdate(
          scanCommerce._id,
          { $inc: { 'scanStats.totalScans': 1 }, $set: { 'scanStats.lastScannedAt': new Date() } }
        );
      }
    } catch {
      // Scan tracking is non-critical — don't fail the request
    }

    console.log(`[PublicController] QR_SCANNED: code=${code}, source=${source}, ip=${ip.slice(0, 8)}...`);

    return res.json({ success: true, message: 'Scan enregistré.' });
  } catch (err) {
    console.error('[PublicController] recordScan error:', err.message);
    return res.status(500).json({ success: false, message: 'Erreur serveur.' });
  }
};

