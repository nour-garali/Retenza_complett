/**
 * Creates a Guest Loyalty Card for a visitor.
 *
 * Logic:
 * 1. Validate all fields
 * 2. Find the commerce by merchantCode
 * 3. Check for existing card (same email OR phone, same merchant) → return existing
 * 4. Generate cardPublicId
 * 5. Create GuestLoyaltyCard in DB
 * 6. Return cardPublicId (no Wallet pass generated here — Lazy approach)
 */
const createGuestCard = async (req, res) => {
  try {
    const { merchantCode, firstName, lastName, email, phone } = req.body;

    // ── 1. Validation ────────────────────────────────────────────────────────
    const missing = ['merchantCode', 'firstName', 'lastName', 'email', 'phone'].filter(
      (f) => !req.body[f]?.trim()
    );
    if (missing.length > 0) {
      return res.status(400).json({
        success: false,
        message: `Champs manquants : ${missing.join(', ')}`,
      });
    }

    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(email)) {
      return res.status(400).json({ success: false, message: "Format d'email invalide." });
    }

    const phoneRegex = /^\+?[\d\s\-().]{7,20}$/;
    if (!phoneRegex.test(phone)) {
      return res.status(400).json({ success: false, message: 'Format de numéro de téléphone invalide.' });
    }

    // ── 2. Find active commerce ──────────────────────────────────────────────
    const commerce = await findCommerceByCode(merchantCode);

    if (!commerce || commerce.status !== 'active') {
      return res.status(404).json({ success: false, message: 'Commerce partenaire introuvable ou inactif.' });
    }

    const normalizedEmail = email.trim().toLowerCase();
    const normalizedPhone = phone.trim();

    // ── 3. Check for existing card (anti-duplicate) ──────────────────────────
    const existingCard = await GuestLoyaltyCard.findOne({
      merchantId: commerce._id,
      $or: [{ email: normalizedEmail }, { phone: normalizedPhone }],
      status: { $ne: 'suspended' },
    });

    if (existingCard) {
      console.log(`[PublicController] Existing card found: ${existingCard.cardPublicId}`);
      return res.json({
        success: true,
        data: {
          cardPublicId: existingCard.cardPublicId,
          isNewCard: false,
          message: `Vous possédez déjà une carte pour ${commerce.name}. Votre carte existante vous a été retournée.`,
        },
      });
    }

    // ── 4. Generate collision-resistant cardPublicId ──────────────────────────
    let cardPublicId;
    let attempts = 0;
    do {
      cardPublicId = generateCardPublicId();
      const collision = await GuestLoyaltyCard.findOne({ cardPublicId });
      if (!collision) break;
      attempts++;
    } while (attempts < 5);

    if (attempts >= 5) {
      return res.status(500).json({ success: false, message: 'Erreur de génération d\'identifiant. Veuillez réessayer.' });
    }

    // ── 5. Create GuestLoyaltyCard ────────────────────────────────────────────
    const card = await GuestLoyaltyCard.create({
      cardPublicId,
      firstName: firstName.trim(),
      lastName: lastName.trim(),
      email: normalizedEmail,
      phone: normalizedPhone,
      merchantId: commerce._id,
      merchantPublicCode: merchantCode.toUpperCase(),
      status: 'active',
      points: 0,
      stamps: 0,
      cashback: 0,
    });

    console.log(`[PublicController] GUEST_CARD_CREATED: ${card.cardPublicId} for commerce ${commerce.name}`);

    // ── 6. Return card info (no Wallet pass here — Lazy approach) ─────────────
    return res.status(201).json({
      success: true,
      data: {
        cardPublicId: card.cardPublicId,
        isNewCard: true,
        message: `Votre carte de fidélité ${commerce.name} a été créée avec succès !`,
      },
    });
  } catch (err) {
    console.error('[PublicController] createGuestCard error:', err.message);
    return res.status(500).json({ success: false, message: 'Erreur lors de la création de la carte.' });
  }
};

