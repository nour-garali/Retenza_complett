/**
 * Generates a Wallet pass ON DEMAND (Lazy Pass Generation).
 * Called only when the user clicks "Add to Google Wallet" or "Add to Apple Wallet".
 *
 * This avoids creating unused passes and reduces API calls to Wallet providers.
 */
const generateWalletPassForGuest = async (req, res) => {
  try {
    const { cardPublicId, provider } = req.body;

    if (!cardPublicId || !provider) {
      return res.status(400).json({ success: false, message: 'cardPublicId et provider sont requis.' });
    }

    if (!['google', 'apple'].includes(provider)) {
      return res.status(400).json({ success: false, message: 'Provider invalide. Valeurs acceptées : google, apple.' });
    }

    // Find the card
    const card = await GuestLoyaltyCard.findOne({ cardPublicId, status: 'active' });
    if (!card) {
      return res.status(404).json({ success: false, message: 'Carte introuvable ou suspendue.' });
    }

    // Find the commerce
    const commerce = await Commerce.findById(card.merchantId);
    if (!commerce || commerce.status !== 'active') {
      return res.status(404).json({ success: false, message: 'Commerce associé introuvable.' });
    }

    // Check if a pass already exists for this provider
    const existingPass = card.walletPasses.find((p) => p.provider === provider);

    if (provider === 'google') {
      // ── Google Wallet ──────────────────────────────────────────────────────
      // Build a synthetic client and loyaltyAccount object compatible with walletService
      const syntheticClient = {
        _id: card._id,
        firstName: card.firstName,
        lastName: card.lastName,
      };

      const syntheticLoyaltyAccount = {
        _id: card._id,
        // cardPublicId → used by walletService as the QR barcode value on the Wallet card.
        // The Flutter app scans this QR to import the card automatically.
        cardPublicId: card.cardPublicId,
        points: card.points,
        stamps: card.stamps,
        cashbackBalance: card.cashback,
        createdAt: card.createdAt,
      };

      const result = await walletService.generateWalletPass(
        syntheticClient,
        commerce,
        syntheticLoyaltyAccount,
        'google'
      );

      // Persist the wallet pass ref if not already stored
      if (!existingPass) {
        card.walletPasses.push({ provider: 'google', objectId: result.objectId });
        await card.save();
      }

      console.log(`[PublicController] WALLET_PASS_GENERATED: google for card ${cardPublicId}`);

      return res.json({
        success: true,
        data: {
          provider: 'google',
          addUrl: result.passUrl,
        },
      });
    }

    if (provider === 'apple') {
      // ── Apple Wallet ───────────────────────────────────────────────────────
      // Apple PassKit integration — placeholder until certificates are configured
      // Structure follows the WalletProvider pattern for easy activation in Phase 3
      const appleObjectId = `apple_guest_${cardPublicId}`;

      if (!existingPass) {
        card.walletPasses.push({ provider: 'apple', objectId: appleObjectId });
        await card.save();
      }

      // TODO Phase 2 Apple: Replace with real PassKit generation
      // const pkpassBuffer = await appleWalletService.generatePass(card, commerce);
      // return res.set('Content-Type', 'application/vnd.apple.pkpass').send(pkpassBuffer);
      const applePassUrl = `${process.env.APP_BASE_URL}/api/public/loyalty-card/${cardPublicId}/apple.pkpass`;

      console.log(`[PublicController] WALLET_PASS_GENERATED: apple for card ${cardPublicId}`);

      return res.json({
        success: true,
        data: {
          provider: 'apple',
          addUrl: applePassUrl,
        },
      });
    }
  } catch (err) {
    console.error('[PublicController] generateWalletPassForGuest error:', err.message);
    return res.status(500).json({ success: false, message: 'Erreur lors de la génération du pass Wallet.' });
  }
};

