/**
 * Manually triggers reconciliation for the authenticated user.
 * Useful if the user registered before they had guest cards,
 * or if they add a new phone number later.
 *
 * Protected endpoint — requires valid JWT (req.user populated by auth middleware).
 */
const manualReconcile = async (req, res) => {
  try {
    const { email, phone } = req.user;

    if (!email && !phone) {
      return res.status(400).json({
        success: false,
        message: 'Aucun email ou téléphone associé à votre compte.',
      });
    }

    const result = await reconcileGuestCards({
      retenzaUserId: req.user._id,
      email: email?.toLowerCase().trim() || '',
      phone: phone?.trim() || '',
    });

    console.log(
      `[PublicController] MANUAL_RECONCILE: userId=${req.user._id} merged=${result.mergedCount}`
    );

    return res.json({
      success: true,
      data: {
        mergedCount: result.mergedCount,
        mergedCards: result.mergedCards,
        message:
          result.mergedCount === 0
            ? 'Aucune carte à importer pour votre compte.'
            : `${result.mergedCount} carte(s) de fidélité importée(s) dans votre compte Retenza !`,
        errors: result.errors.length > 0 ? result.errors : undefined,
      },
    });
  } catch (err) {
    console.error('[PublicController] manualReconcile error:', err.message);
    return res.status(500).json({ success: false, message: 'Erreur lors de la réconciliation.' });
  }
};

// ─────────────────────────────────────────────────────────────────────────────
// GET /api/public/loyalty-card/lookup/:cardPublicId
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Looks up a GuestLoyaltyCard by its cardPublicId.
 *
 * Used by the Retenza Flutter app when scanning the QR on a Wallet pass.
 * Returns only the minimum info needed to confirm the card and trigger
 * reconciliation — no sensitive data (email/phone) is exposed.
 *
 * Flow:
 *   App scans QR → reads "RTC-XXXX-XXXX" → calls this endpoint
 *   → displays "Found card for Café ABC" → user confirms → reconcile()
 */
const lookupCardByPublicId = async (req, res) => {
  try {
    const { cardPublicId } = req.params;

    if (!cardPublicId || !/^RTC-[A-Z0-9]{4}-[A-Z0-9]{4}$/i.test(cardPublicId)) {
      return res.status(400).json({ success: false, message: 'Format de cardPublicId invalide.' });
    }

    const card = await GuestLoyaltyCard.findOne({
      cardPublicId: cardPublicId.toUpperCase(),
    }).select('cardPublicId merchantPublicCode merchantId status firstName createdAt');

    if (!card) {
      return res.status(404).json({ success: false, message: 'Carte introuvable.' });
    }

    // Get commerce name for display
    const commerce = await Commerce.findById(card.merchantId).select('name category brandColor logo');

    return res.json({
      success: true,
      data: {
        cardPublicId: card.cardPublicId,
        status: card.status,
        createdAt: card.createdAt,
        // First name only — enough to confirm "Yes, this is my card" without exposing full identity
        firstName: card.firstName,
        merchant: commerce
          ? {
              name: commerce.name,
              category: commerce.category,
              brandColor: commerce.brandColor,
              logoUrl: commerce.logo,
              publicCode: card.merchantPublicCode,
            }
          : { name: 'Commerce inconnu', publicCode: card.merchantPublicCode },
      },
    });
  } catch (err) {
    console.error('[PublicController] lookupCardByPublicId error:', err.message);
    return res.status(500).json({ success: false, message: 'Erreur serveur.' });
  }
};

