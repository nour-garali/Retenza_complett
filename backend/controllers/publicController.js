/**
 * publicController.js
 *
 * Handles all public endpoints (no authentication required).
 * These are called when a customer scans a merchant QR Code without the Retanza app.
 *
 * Endpoints:
 *   GET  /api/public/merchant/:code          → Public merchant profile
 *   POST /api/public/merchant/:code/scan     → Record QR scan for statistics
 *   POST /api/public/loyalty-card/create     → Create a Guest Loyalty Card
 *   POST /api/public/loyalty-card/wallet-pass → Generate a Wallet pass on demand (Lazy)
 */

const Commerce = require('../models/Commerce');
const QRCode = require('../models/QRCode');
const GuestLoyaltyCard = require('../models/GuestLoyaltyCard');
const walletService = require('../services/walletService');
const { reconcileGuestCards } = require('../services/reconciliationService');

/**
 * Finds a Commerce by QR code.
 * Strategy:
 *   1. Try Commerce.merchantCode (new format, M###### or RC-XXXX)
 *   2. Fall back to QRCode collection (stores the RC-XXXXXXXX code separately)
 * This handles both old and new merchants transparently.
 */
const findCommerceByCode = async (code) => {
  const upperCode = code.toUpperCase();

  // Strategy 1: direct merchantCode match
  let commerce = await Commerce.findOne({ merchantCode: upperCode }).select(
    'name category description logo coverImage brandColor contact loyaltyProgram status merchantCode'
  );
  if (commerce) return commerce;

  // Strategy 2: look up in QRCode collection (code generated by generateQRCode endpoint)
  const qrDoc = await QRCode.findOne({ code: upperCode }).select('commerce');
  if (!qrDoc) return null;

  commerce = await Commerce.findById(qrDoc.commerce).select(
    'name category description logo coverImage brandColor contact loyaltyProgram status merchantCode'
  );
  return commerce;
};


// ── Helpers ──────────────────────────────────────────────────────────────────

/**
 * Generates a unique, collision-resistant public card ID.
 * Format: RTC-XXXX-XXXX (alphanumeric, no ambiguous chars like O/0 I/1)
 */
const generateCardPublicId = () => {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  const segment = () =>
    Array.from({ length: 4 }, () => chars[Math.floor(Math.random() * chars.length)]).join('');
  return `RTC-${segment()}-${segment()}`;
};

/**
 * Maps a Commerce document to the public profile shape expected by the frontend.
 * Never exposes internal IDs, merchant contacts, or sensitive data.
 */
const toPublicProfile = (commerce) => ({
  name: commerce.name,
  category: commerce.category,
  description: commerce.description || '',
  logoUrl: commerce.logo || null,
  bannerUrl: commerce.coverImage || null,
  primaryColor: commerce.brandColor || '#D73E26',
  secondaryColor: '#FFFFFF',
  address: commerce.contact?.address
    ? `${commerce.contact.address}${commerce.contact.city ? ', ' + commerce.contact.city : ''}`
    : null,
  loyaltyProgram: {
    type: commerce.loyaltyProgram?.type || 'points',
    totalStamps: commerce.loyaltyProgram?.stampsRequired,
    currentStamps: 0,
    reward: commerce.loyaltyProgram?.rewardDescription,
    pointsPerEuro: commerce.loyaltyProgram?.pointsPerEuro,
    cashbackRate: commerce.loyaltyProgram?.cashbackPercentage,
  },
  isActive: commerce.status === 'active',
});

// ── In-memory scan deduplication (production: use Redis) ─────────────────────
// Key: `${ip}:${code}` | Value: timestamp of last recorded scan
const scanDedup = new Map();
const SCAN_DEDUP_TTL_MS = 60 * 60 * 1000; // 1 hour

// ─────────────────────────────────────────────────────────────────────────────
// GET /api/public/merchant/:code
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Returns the public profile of a merchant by their QR merchantCode.
 * Also increments QR scan count for basic statistics.
 */
const getPublicMerchant = async (req, res) => {
  try {
    const { code } = req.params;

    // Validate format
    if (!code || !/^[A-Z0-9-]{3,20}$/i.test(code)) {
      return res.status(400).json({ success: false, message: 'Code commerçant invalide.' });
    }

    const commerce = await findCommerceByCode(code);

    if (!commerce) {
      return res.status(404).json({ success: false, message: 'Commerce introuvable.' });
    }

    if (commerce.status !== 'active') {
      return res.status(403).json({
        success: false,
        message: 'Ce commerce ne fait plus partie du réseau Retenza.',
      });
    }

    return res.json({
      success: true,
      data: toPublicProfile(commerce),
    });
  } catch (err) {
    console.error('[PublicController] getPublicMerchant error:', err.message);
    return res.status(500).json({ success: false, message: 'Erreur serveur.' });
  }
};

